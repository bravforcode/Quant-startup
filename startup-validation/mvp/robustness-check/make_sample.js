// Writes a synthetic trade history for demos. The numbers are random and do not describe any real strategy.
// Run:  node startup-validation/mvp/robustness-check/make_sample.js
const fs = require("node:fs");
const path = require("node:path");
const R = require("./engine.js");

const rand = R.mulberry32(20261020);
const gauss = () => {
  // Box-Muller transform on the seeded generator
  const u = Math.max(rand(), 1e-9);
  const v = rand();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
};

const rows = ["close_time,profit"];
let day = Date.UTC(2026, 0, 5, 10, 0);
for (let i = 0; i < 150; i++) {
  const d = new Date(day + i * 36 * 60 * 60 * 1000);
  const stamp = `${d.getUTCFullYear()}.${String(d.getUTCMonth() + 1).padStart(2, "0")}.${String(d.getUTCDate()).padStart(2, "0")} ${String(d.getUTCHours()).padStart(2, "0")}:00`;
  const profit = Math.round((6 + 22 * gauss()) * 100) / 100;
  rows.push(`${stamp},${profit}`);
}
const csv = rows.join("\n") + "\n";

const dir = __dirname;
fs.writeFileSync(path.join(dir, "sample", "synthetic_trades.csv"), csv);
fs.writeFileSync(
  path.join(dir, "sample_data.js"),
  "// Synthetic demo data generated by make_sample.js. Not a real strategy.\n" +
    "window.SAMPLE_TRADES_CSV = " + JSON.stringify(csv) + ";\n",
);
console.log(`wrote ${rows.length - 1} synthetic trades`);
